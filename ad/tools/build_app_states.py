# Turns the real app's CSS + DOM snapshots (captured by appshots.js) into film/app_states.js for Shadow-DOM phone screens.
import re, json, sys, os
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))   # repo root
SNAP = os.path.join(ROOT, 'ad/tools/app_snapshots')
css = open(os.path.join(ROOT, 'styles.css')).read()

def strip_media(s):
    out, i = [], 0
    while True:
        j = s.find('@media', i)
        if j < 0: out.append(s[i:]); break
        out.append(s[i:j]); k = s.index('{', j); depth = 1; k += 1
        while depth: depth += {'{': 1, '}': -1}.get(s[k], 0); k += 1
        i = k
    return ''.join(out)

css = strip_media(css)                      # every query targets tablets / short / landscape screens, never a 390×844 phone
css = css.replace(':root', ':host')
css = re.sub(r'\bhtml,\s*body\b', ':host', css)
css = re.sub(r'\b(?:body|html)((?:\.[\w-]+)+)', r':host(\1)', css)
css = re.sub(r'(^|[\s,}])body(\s*[{,])', r'\1:host\2', css)
css += '''
:host{display:block;position:relative;overflow:hidden;width:390px;height:var(--ph,760px);font-family:"Inter",system-ui,sans-serif;background:var(--bg)}
#app{height:100%}
*{transition:none!important;animation:none!important}
'''
def body(name):
    s = open(os.path.join(SNAP, name + '.html')).read()
    app, rest = s.split('<!--player-->')
    player, toast = rest.split('<!--toast-->')
    fix = lambda h: re.sub(r'(<img[^>]*?)\ssrc="[^"]*"([^>]*?data-cover="(c\d)")', r'\1 src="covers/\3.jpg"\2', h)
    fix2 = lambda h: re.sub(r'https://cdn\.test/(c\d)\.jpg', r'covers/\1.jpg', fix(h))
    return {'app': fix2(app.strip()), 'player': fix(player.strip()), 'toast': toast.strip()}
S = {k: body(v) for k, v in {'add_empty': '10_add_empty', 'add_preview': '12_add_preview', 'add_saved': '14_add_saved',
     'library': '24_library_playing', 'playlist': '22_playlist_playing', 'player': '23_player'}.items()}
for k, v in S.items():
    left = re.findall(r'src="(blob:[^"]*|https://cdn[^"]*)"', v['app'] + v['player'])
    print(k, 'unmapped imgs:', len(left))
out = '// generated by ad/tools/build_app_states.py from styles.css + real DOM snapshots of Tikify — do not edit\n'
out += 'window.APP_CSS = ' + json.dumps(css) + ';\nwindow.APP_STATES = ' + json.dumps(S) + ';\n'
open(os.path.join(ROOT, 'ad/film/app_states.js'), 'w').write(out)
print('css', len(css), 'bytes; ->', 'ad/film/app_states.js')
